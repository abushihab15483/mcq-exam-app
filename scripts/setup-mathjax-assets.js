#!/usr/bin/env node
/**
 * Issue #10 fix — self-host MathJax instead of loading it from an external CDN.
 *
 * `better-react-mathjax` defaults to fetching MathJax from
 * https://cdnjs.cloudflare.com/... at runtime. On a restricted school network,
 * a blocked CDN, or a DNS problem, that request never resolves, and math
 * stops rendering for every student on that network.
 *
 * Instead of committing large binary MathJax assets to git, this script
 * copies the exact files we need out of `node_modules/mathjax-full`
 * (a pinned, version-locked dependency — see package.json) into
 * `public/vendor/mathjax/` right after `npm install`. That keeps the
 * self-hosted bundle reproducible and in sync with the pinned version,
 * without bloating the git repo.
 *
 * Only the pieces the app actually uses are copied:
 *   - tex-mml-chtml.js   → the same combined component MathProvider already
 *                          configured (TeX input + MathML + CHTML output)
 *   - input/asciimath.js → dynamically loaded by MathProvider's
 *                          `loader: { load: ["input/asciimath"] }` config;
 *                          MathJax fetches this itself at runtime relative
 *                          to wherever tex-mml-chtml.js was loaded from, so
 *                          it must sit next to it locally too.
 *   - output/chtml/**     → CHTML output's font metrics (fonts/tex.js) and
 *                          the actual .woff glyph files it references at
 *                          render time for math symbols.
 *
 * Safe to run repeatedly (used in `postinstall`, `predev`, and `prebuild`).
 */

const fs = require("fs");
const path = require("path");

const SRC_ROOT = path.join(__dirname, "..", "node_modules", "mathjax-full", "es5");
const DEST_ROOT = path.join(__dirname, "..", "public", "vendor", "mathjax");

// Relative to SRC_ROOT / DEST_ROOT.
const FILES_TO_COPY = ["tex-mml-chtml.js", "input/asciimath.js"];
const DIRS_TO_COPY = ["output/chtml"];

function copyFile(relPath) {
  const src = path.join(SRC_ROOT, relPath);
  const dest = path.join(DEST_ROOT, relPath);
  if (!fs.existsSync(src)) {
    throw new Error(
      `[mathjax-assets] Expected source file not found: ${src}\n` +
        `Did the "mathjax-full" dependency version change? Re-check scripts/setup-mathjax-assets.js.`
    );
  }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
}

function copyDir(relPath) {
  const src = path.join(SRC_ROOT, relPath);
  const dest = path.join(DEST_ROOT, relPath);
  if (!fs.existsSync(src)) {
    throw new Error(`[mathjax-assets] Expected source directory not found: ${src}`);
  }
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, entry.name);
    const d = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDir(path.join(relPath, entry.name));
    } else {
      fs.copyFileSync(s, d);
    }
  }
}

function main() {
  if (!fs.existsSync(SRC_ROOT)) {
    console.warn(
      `[mathjax-assets] node_modules/mathjax-full/es5 not found — skipping ` +
        `(this is expected if "npm install" has not finished yet; ` +
        `postinstall will run this again).`
    );
    return;
  }

  for (const f of FILES_TO_COPY) copyFile(f);
  for (const d of DIRS_TO_COPY) copyDir(d);

  // Small marker file so we can tell at a glance (and in CI) which pinned
  // mathjax-full version the self-hosted assets came from.
  const pkgJsonPath = path.join(__dirname, "..", "node_modules", "mathjax-full", "package.json");
  let version = "unknown";
  try {
    version = JSON.parse(fs.readFileSync(pkgJsonPath, "utf8")).version;
  } catch {
    // Non-fatal — version stamp is informational only.
  }
  fs.writeFileSync(
    path.join(DEST_ROOT, "VERSION.txt"),
    `mathjax-full ${version}\ngenerated by scripts/setup-mathjax-assets.js — do not edit by hand.\n`
  );

  console.log(`[mathjax-assets] Self-hosted MathJax assets ready in public/vendor/mathjax (mathjax-full ${version}).`);
}

main();
